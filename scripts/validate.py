"""Check Radiocity's models against independent references.

    python scripts/validate.py      # writes results/validation.csv and results/VALIDATION.md

Every check compares a number computed by Radiocity with a number that
Radiocity did not produce: an exact physical law, an independent solar
model (PVGIS, European Commission JRC; responses saved in data/validation/),
or a published measurement.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from radiocity.harvesters import (  # noqa: E402
    InductiveLink,
    SolarPV,
    Thermophotovoltaic,
    rectifier_efficiency,
)
from radiocity.planck_model import integrate_band  # noqa: E402
from radiocity.radiative_transfer import blackbody_emissive_power  # noqa: E402
from radiocity.scenarios import CITIES, load_climate  # noqa: E402

VALIDATION_DIR = ROOT / "data" / "validation"
RESULTS = ROOT / "results"


def planck_checks() -> list[dict]:
    rows = []
    for temperature in (300.0, 1000.0, 1500.0):
        ours = integrate_band(1e-8, 1e-3, temperature, samples=20000)
        exact = blackbody_emissive_power(temperature)
        rows.append({
            "check": f"Blackbody power at {temperature:.0f} K",
            "radiocity": f"{ours:,.0f} W/m²",
            "reference": f"{exact:,.0f} W/m² (Stefan-Boltzmann law, exact)",
            "difference": f"{abs(100 * (ours / exact - 1)):.2f}%",
            "kind": "Exact physical law",
        })
    return rows


def pvgis_checks() -> list[dict]:
    rows = []
    for city, label in CITIES.items():
        pvgis = json.loads((VALIDATION_DIR / f"pvgis_{city}_horizontal_1kwp.json").read_text())
        totals = pvgis["outputs"]["totals"]["fixed"]
        panel = SolarPV("1kWp", area_m2=1000 / (0.22 * 1000), efficiency_stc=0.22, system_efficiency=0.92)
        climate = load_climate(city)
        ours = sum(panel.power_w(row) for row in climate.to_dict("records")) / 1000
        rows.append({
            "check": f"Yearly solar yield, {label} (1 kW horizontal, 8% system loss)",
            "radiocity": f"{ours:,.0f} kWh",
            "reference": f"{totals['E_y']:,.0f} kWh (PVGIS 5.3, SARAH-3 satellite data 2005-2023)",
            "difference": f"{100 * (ours / totals['E_y'] - 1):+.1f}%",
            "kind": "Independent model, different weather data",
        })
    return rows


def published_checks() -> list[dict]:
    best = max(
        (Thermophotovoltaic("t", 1.0, bandgap_ev=gap / 100).efficiency(2400.0), gap / 100)
        for gap in range(60, 160, 2)
    )
    link = InductiveLink("pad", 1000.0).power_w({"inductive_available": 1.0}) / 1000.0
    return [
        {
            "check": "Best heat-to-electricity (TPV) efficiency, ~2400 K source",
            "radiocity": f"{best[0]:.1%} (bandgap {best[1]:.2f} eV)",
            "reference": "~40% measured (LaPotin et al., Nature 2022; 1.0-1.4 eV cells, ~2000-2400 °C emitters)",
            "difference": f"{100 * (best[0] / 0.40 - 1):+.0f}%",
            "kind": "Published measurement",
        },
        {
            "check": "Wireless charging pad, end-to-end efficiency (aligned)",
            "radiocity": f"{link:.0%}",
            "reference": "≥85% efficiency target for aligned wireless EV charging (SAE J2954)",
            "difference": "meets target" if link >= 0.85 else "below target",
            "kind": "Industry standard",
        },
        {
            "check": "Radio rectifier efficiency at 0 / -10 / -20 / -30 dBm input",
            "radiocity": " / ".join(f"{rectifier_efficiency(10 ** (d / 10) / 1000):.0%}" for d in (0, -10, -20, -30)),
            "reference": "Falls from tens of % near 0 dBm to a few % at -30 dBm (survey: Valenta & Durgin, 2014)",
            "difference": "same trend; calibrate to a specific rectifier",
            "kind": "Published survey (qualitative)",
        },
    ]


def main() -> None:
    rows = planck_checks() + pvgis_checks() + published_checks()
    table = pd.DataFrame(rows)
    RESULTS.mkdir(exist_ok=True)
    table.to_csv(RESULTS / "validation.csv", index=False)

    lines = [
        "# Validation",
        "",
        "Generated by `python scripts/validate.py`. Each row compares a number Radiocity computes with one it did not "
        "produce: an exact law of physics, an independent solar model run by the European Commission (PVGIS), or a "
        "published measurement.",
        "",
        "| Check | Radiocity | Reference | Difference |",
        "|---|---|---|---|",
        *[f"| {r['check']} | {r['radiocity']} | {r['reference']} | {r['difference']} |" for r in rows],
        "",
        "**Solar yield:** Radiocity is 4-7% *below* PVGIS in every city, so it does not overstate solar energy. "
        "Most of the gap is the weather data itself: Radiocity uses NASA POWER data for the single year 2024, which "
        "was 6-10% less sunny than PVGIS's 2005-2023 satellite average. Per unit of sunlight, the two conversion "
        "models agree to within about 1-3%.",
        "",
        "**Next level of evidence:** a field measurement with real hardware - see [docs/FIELD_TEST.md](../docs/FIELD_TEST.md).",
        "",
    ]
    (RESULTS / "VALIDATION.md").write_text("\n".join(lines))
    print(table.to_string(index=False))


if __name__ == "__main__":
    main()
